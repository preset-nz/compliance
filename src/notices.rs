//! `preset-compliance notices`: one plain-text file holding the licence text of
//! every shipped package, so the copyright notices MIT, BSD and Apache ask for
//! travel with the binary. Reads the committed lock and the packages as
//! installed on this machine; never touches the network.
//!
//! Two halves. Discovery (cargo metadata, `node_modules/.pnpm`, a uv venv)
//! finds each package's licence files and is thin on purpose. Rendering takes
//! plain values and returns bytes: sorted, no timestamps, so the same inputs
//! give the same file.

use crate::adapters::cargo;
use crate::config::Config;
use crate::lock::{self, Lock};
use crate::model::{Ecosystem, Package, Scope};
use anyhow::{Context, Result};
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

pub const DEFAULT_TITLE: &str = "Third-party notices";
pub const DEFAULT_OUT: &str = "THIRD-PARTY-NOTICES.txt";

/// Licence files larger than this are skipped: a bundled dataset or a
/// changelog named NOTICE, not a licence.
const MAX_FILE_BYTES: u64 = 256 * 1024;

const RULE_HEAVY: &str =
    "================================================================================";
const RULE_LIGHT: &str =
    "--------------------------------------------------------------------------------";

/// What `write` reports.
pub struct Summary {
    pub packages: usize,
    pub with_text: usize,
    pub without_text: usize,
}

/// A shipped package and the licence text found for it, if any.
#[derive(Debug, Clone)]
pub struct Entry {
    pub package: Package,
    pub text: Option<String>,
}

/// Packages whose licence text is byte-identical, printed once.
#[derive(Debug, PartialEq, Eq)]
pub struct Group<'a> {
    pub packages: Vec<&'a Package>,
    pub text: &'a str,
}

pub fn write(
    root: &Path,
    config: &Config,
    lock: &Lock,
    title: &str,
    out: &Path,
) -> Result<Summary> {
    let lock_bytes = std::fs::read(root.join(lock::FILE_NAME))
        .with_context(|| format!("reading {}", lock::FILE_NAME))?;
    let lock_sha = hex(&Sha256::digest(&lock_bytes));

    let mut extras = Vec::new();
    for path in &config.notices.extras {
        let text = std::fs::read_to_string(root.join(path))
            .with_context(|| format!("reading notices extra `{path}`"))?;
        extras.push((path.clone(), text));
    }

    let locator = Locator::new(root, lock);
    let entries: Vec<Entry> = lock
        .packages
        .iter()
        .filter(|p| p.scope == Scope::Shipped)
        .map(|p| Entry {
            package: p.clone(),
            text: licence_text(&locator.dirs(p)),
        })
        .collect();

    let summary = Summary {
        packages: entries.len(),
        with_text: entries.iter().filter(|e| e.text.is_some()).count(),
        without_text: entries.iter().filter(|e| e.text.is_none()).count(),
    };
    let rendered = render(title, &lock_sha, &extras, &entries);
    std::fs::write(out, rendered).with_context(|| format!("writing {}", out.display()))?;
    Ok(summary)
}

// ---- rendering (pure) -------------------------------------------------------

/// The whole file. Entries and extras may arrive in any order.
pub fn render(
    title: &str,
    lock_sha: &str,
    extras: &[(String, String)],
    entries: &[Entry],
) -> String {
    let mut out = String::new();
    out.push_str(title);
    out.push('\n');
    out.push_str(RULE_HEAVY);
    out.push('\n');
    out.push_str(&format!(
        "Generated by preset-compliance notices from {} (sha256 {lock_sha}).\n",
        lock::FILE_NAME
    ));
    out.push_str("This file lists every package in shipped scope with its licence text.\n");

    for (path, text) in extras {
        out.push_str(&format!("\n{RULE_HEAVY}\n{path}\n{RULE_HEAVY}\n\n"));
        out.push_str(text.trim_end());
        out.push('\n');
    }

    let (groups, missing) = group(entries);
    for group in &groups {
        out.push_str(&format!("\n{RULE_HEAVY}\n"));
        for p in &group.packages {
            out.push_str(&package_line(p));
            out.push('\n');
        }
        out.push_str(&format!("{RULE_LIGHT}\n{}\n", group.text));
    }

    if !missing.is_empty() {
        out.push_str(&format!(
            "\n{RULE_HEAVY}\nLicence text not included in the package\n{RULE_HEAVY}\n\n"
        ));
        for p in missing {
            out.push_str(&format!(
                "{} {} ({}) — {}\n",
                p.name,
                p.version,
                p.ecosystem,
                p.declared.as_deref().unwrap_or("undeclared")
            ));
        }
    }
    out
}

fn package_line(p: &Package) -> String {
    format!(
        "{} {} ({}) — {}",
        p.name,
        p.version,
        p.ecosystem,
        p.declared.as_deref().unwrap_or("undeclared")
    )
}

/// Groups by identical text, each group ordered by its first package, plus the
/// packages with no text, sorted.
pub fn group(entries: &[Entry]) -> (Vec<Group<'_>>, Vec<&Package>) {
    let mut by_text: BTreeMap<&str, Vec<&Package>> = BTreeMap::new();
    let mut missing = Vec::new();
    for entry in entries {
        match entry.text.as_deref() {
            Some(text) => by_text.entry(text).or_default().push(&entry.package),
            None => missing.push(&entry.package),
        }
    }
    let mut groups: Vec<Group> = by_text
        .into_iter()
        .map(|(text, mut packages)| {
            packages.sort();
            packages.dedup();
            Group { packages, text }
        })
        .collect();
    // Packages order by ecosystem first; the brief orders groups by name.
    groups.sort_by(|a, b| {
        let key = |g: &Group| (g.packages[0].name.clone(), g.packages[0].version.clone());
        key(a).cmp(&key(b)).then_with(|| a.text.cmp(b.text))
    });
    missing.sort_by(|a, b| (&a.name, &a.version).cmp(&(&b.name, &b.version)));
    (groups, missing)
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

// ---- file names (pure) ------------------------------------------------------

/// A top-level file that carries a licence or a notice: LICENSE, LICENCE,
/// COPYING, NOTICE or THIRD_PARTY_NOTICES, with any extension or suffix.
pub fn is_licence_file(name: &str) -> bool {
    let upper = name.to_ascii_uppercase();
    [
        "LICENSE",
        "LICENCE",
        "COPYING",
        "NOTICE",
        "THIRD_PARTY_NOTICES",
        "THIRD-PARTY-NOTICES",
    ]
    .iter()
    .any(|prefix| upper.starts_with(prefix))
}

/// Whether a `node_modules/.pnpm` entry is this package: `<enc>@<version>`,
/// optionally followed by a `_peer...` suffix. `enc` is the name with `/`
/// replaced by `+`.
pub fn pnpm_entry_matches(entry: &str, name: &str, version: &str) -> bool {
    let exact = format!("{}@{version}", name.replace('/', "+"));
    entry == exact
        || entry
            .strip_prefix(&exact)
            .is_some_and(|rest| rest.starts_with('_'))
}

/// A Python distribution name as it appears in a `.dist-info` directory:
/// lowercase, runs of `-`, `_` and `.` collapsed to one `_`.
pub fn uv_dist_name(name: &str) -> String {
    let mut out = String::new();
    let mut separator = false;
    for c in name.chars() {
        if matches!(c, '-' | '_' | '.') {
            separator = true;
        } else {
            if separator {
                out.push('_');
                separator = false;
            }
            out.push(c.to_ascii_lowercase());
        }
    }
    if separator {
        out.push('_');
    }
    out
}

// ---- discovery (thin) -------------------------------------------------------

/// Where installed packages can be found on this machine.
struct Locator {
    cargo: BTreeMap<(String, String), PathBuf>,
    /// Directories holding `node_modules`, one per pnpm lockfile.
    pnpm_roots: Vec<PathBuf>,
    /// Directories holding `.venv`, one per uv lockfile.
    uv_roots: Vec<PathBuf>,
}

impl Locator {
    fn new(root: &Path, lock: &Lock) -> Locator {
        let mut locator = Locator {
            cargo: BTreeMap::new(),
            pnpm_roots: Vec::new(),
            uv_roots: Vec::new(),
        };
        for input in &lock.inputs {
            let Some(ecosystem) = input.ecosystem else {
                continue;
            };
            let dir = root.join(&input.path).parent().map(Path::to_path_buf);
            let Some(dir) = dir else { continue };
            match ecosystem {
                Ecosystem::Cargo => match cargo::package_dirs(&dir.join("Cargo.toml")) {
                    Ok(found) => locator.cargo.extend(found),
                    // Report, don't gate: those crates land under "not included".
                    Err(error) => eprintln!("warning: {error:#}"),
                },
                Ecosystem::Pnpm => locator.pnpm_roots.push(dir),
                Ecosystem::Uv => locator.uv_roots.push(dir),
            }
        }
        locator
    }

    /// Directories to look for licence files in, best first.
    fn dirs(&self, p: &Package) -> Vec<PathBuf> {
        match p.ecosystem {
            Ecosystem::Cargo => self
                .cargo
                .get(&(p.name.clone(), p.version.clone()))
                .cloned()
                .into_iter()
                .collect(),
            Ecosystem::Pnpm => self
                .pnpm_roots
                .iter()
                .flat_map(|r| pnpm_dirs(r, &p.name, &p.version))
                .collect(),
            Ecosystem::Uv => self
                .uv_roots
                .iter()
                .flat_map(|r| uv_dirs(r, &p.name, &p.version))
                .collect(),
        }
    }
}

fn sorted_entries(dir: &Path) -> Vec<(String, PathBuf)> {
    let Ok(read) = std::fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut entries: Vec<(String, PathBuf)> = read
        .filter_map(Result::ok)
        .map(|e| (e.file_name().to_string_lossy().into_owned(), e.path()))
        .collect();
    entries.sort();
    entries
}

fn pnpm_dirs(root: &Path, name: &str, version: &str) -> Vec<PathBuf> {
    sorted_entries(&root.join("node_modules/.pnpm"))
        .into_iter()
        .filter(|(entry, _)| pnpm_entry_matches(entry, name, version))
        .map(|(_, path)| path.join("node_modules").join(name))
        .filter(|path| path.is_dir())
        .collect()
}

fn uv_dirs(root: &Path, name: &str, version: &str) -> Vec<PathBuf> {
    let dist_info = format!("{}-{version}.dist-info", uv_dist_name(name));
    let mut dirs = Vec::new();
    for (entry, python) in sorted_entries(&root.join(".venv/lib")) {
        if !entry.starts_with("python") {
            continue;
        }
        let info = python.join("site-packages").join(&dist_info);
        if info.is_dir() {
            dirs.push(info.join("licenses"));
            dirs.push(info);
        }
    }
    dirs
}

/// The licence files of the first directory that has any, as one text. One
/// file is the text as it is; several are each led by a `[name]` line.
/// Line endings are normalised so identical texts group.
fn licence_text(dirs: &[PathBuf]) -> Option<String> {
    for dir in dirs {
        let mut files = Vec::new();
        for (name, path) in sorted_entries(dir) {
            if !is_licence_file(&name) || !path.is_file() {
                continue;
            }
            let small = std::fs::metadata(&path).is_ok_and(|m| m.len() <= MAX_FILE_BYTES);
            let Ok(bytes) = std::fs::read(&path) else {
                continue;
            };
            if small {
                let text = String::from_utf8_lossy(&bytes).replace("\r\n", "\n");
                let text = text.trim().to_string();
                if !text.is_empty() {
                    files.push((name, text));
                }
            }
        }
        if let Some(text) = join_files(&files) {
            return Some(text);
        }
    }
    None
}

fn join_files(files: &[(String, String)]) -> Option<String> {
    match files {
        [] => None,
        [(_, text)] => Some(text.clone()),
        _ => Some(
            files
                .iter()
                .map(|(name, text)| format!("[{name}]\n{text}"))
                .collect::<Vec<_>>()
                .join("\n\n"),
        ),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::Source;

    fn package(name: &str, declared: Option<&str>) -> Package {
        Package {
            ecosystem: Ecosystem::Cargo,
            name: name.into(),
            version: "1.0.0".into(),
            source: Source::Registry,
            declared: declared.map(String::from),
            scope: Scope::Shipped,
        }
    }

    fn entry(name: &str, text: Option<&str>) -> Entry {
        Entry {
            package: package(name, Some("MIT")),
            text: text.map(String::from),
        }
    }

    #[test]
    fn licence_file_names() {
        for yes in [
            "LICENSE",
            "license.md",
            "LICENCE-MIT",
            "LICENSE-APACHE",
            "COPYING",
            "COPYING.LESSER",
            "NOTICE",
            "NOTICE.txt",
            "THIRD_PARTY_NOTICES.md",
            "third-party-notices.txt",
        ] {
            assert!(is_licence_file(yes), "{yes}");
        }
        for no in [
            "README.md",
            "package.json",
            "Cargo.toml",
            "src",
            "CHANGELOG",
            "MIT-LICENSE",
        ] {
            assert!(!is_licence_file(no), "{no}");
        }
    }

    #[test]
    fn pnpm_entries_match_with_and_without_peer_suffix() {
        assert!(pnpm_entry_matches("react@19.3.0", "react", "19.3.0"));
        assert!(pnpm_entry_matches(
            "facets@0.1.3_react@19.3.0",
            "facets",
            "0.1.3"
        ));
        assert!(pnpm_entry_matches(
            "@tauri-apps+api@2.1.0",
            "@tauri-apps/api",
            "2.1.0"
        ));
        assert!(pnpm_entry_matches(
            "@radix-ui+react-slot@1.2.0_@types+react@19.0.0",
            "@radix-ui/react-slot",
            "1.2.0"
        ));
        // A longer version or a different name is not a match.
        assert!(!pnpm_entry_matches("react@19.3.01", "react", "19.3.0"));
        assert!(!pnpm_entry_matches("react-dom@19.3.0", "react", "19.3.0"));
        assert!(!pnpm_entry_matches("@tauri-apps+api@2.1.0", "api", "2.1.0"));
    }

    #[test]
    fn uv_names_are_normalised() {
        assert_eq!(uv_dist_name("Pillow"), "pillow");
        assert_eq!(uv_dist_name("typing-extensions"), "typing_extensions");
        assert_eq!(uv_dist_name("zope.interface"), "zope_interface");
        assert_eq!(uv_dist_name("a-_.b"), "a_b");
    }

    #[test]
    fn identical_texts_group_and_groups_order_by_first_package() {
        let entries = vec![
            entry("zeta", Some("MIT text")),
            entry("alpha", Some("Apache text")),
            entry("beta", Some("MIT text")),
            entry("gamma", None),
        ];
        let (groups, missing) = group(&entries);
        assert_eq!(groups.len(), 2);
        assert_eq!(groups[0].text, "Apache text");
        let names: Vec<_> = groups[1].packages.iter().map(|p| &p.name[..]).collect();
        assert_eq!(names, ["beta", "zeta"]);
        assert_eq!(groups[1].text, "MIT text");
        assert_eq!(missing.len(), 1);
        assert_eq!(missing[0].name, "gamma");
    }

    #[test]
    fn render_is_deterministic_and_independent_of_input_order() {
        let a = vec![
            entry("b", Some("Text B")),
            entry("a", Some("Text A")),
            Entry {
                package: package("c", None),
                text: None,
            },
        ];
        let mut b = a.clone();
        b.reverse();
        let extras = vec![("EXTRA.md".to_string(), "Model licence\n\n".to_string())];
        let one = render("Notices", "abc123", &extras, &a);
        assert_eq!(one, render("Notices", "abc123", &extras, &b));
        assert!(one.starts_with("Notices\n"));
        assert!(one.contains(
            "Generated by preset-compliance notices from preset-compliance.lock (sha256 abc123)."
        ));
        assert!(one.contains("EXTRA.md\n"));
        assert!(one.contains("Model licence\n"));
        assert!(one.contains("a 1.0.0 (cargo) — MIT\n"));
        assert!(one.find("Text A").unwrap() < one.find("Text B").unwrap());
        assert!(
            one.trim_end()
                .ends_with("Licence text not included in the package\n================================================================================\n\nc 1.0.0 (cargo) — undeclared")
        );
    }

    #[test]
    fn no_missing_section_when_everything_has_text() {
        let out = render("T", "x", &[], &[entry("a", Some("A"))]);
        assert!(!out.contains("not included"));
    }

    #[test]
    fn several_licence_files_are_labelled_one_is_not() {
        assert_eq!(
            join_files(&[("LICENSE".into(), "MIT".into())]).unwrap(),
            "MIT"
        );
        assert_eq!(
            join_files(&[
                ("LICENSE-A".into(), "A".into()),
                ("NOTICE".into(), "N".into())
            ])
            .unwrap(),
            "[LICENSE-A]\nA\n\n[NOTICE]\nN"
        );
        assert!(join_files(&[]).is_none());
    }

    #[test]
    fn licence_text_reads_files_skips_big_ones_and_prefers_first_dir() {
        let dir = tempfile::tempdir().unwrap();
        let empty = dir.path().join("empty");
        let full = dir.path().join("full");
        std::fs::create_dir_all(&empty).unwrap();
        std::fs::create_dir_all(&full).unwrap();
        std::fs::write(empty.join("README"), "no").unwrap();
        std::fs::write(full.join("LICENSE"), "MIT\r\n\r\n").unwrap();
        std::fs::write(full.join("NOTICE"), vec![b'x'; 300 * 1024]).unwrap();
        let text = licence_text(&[empty, full]).unwrap();
        assert_eq!(text, "MIT");
    }
}
